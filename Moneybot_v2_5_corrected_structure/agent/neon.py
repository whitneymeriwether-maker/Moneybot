"""Neon PostgreSQL connectivity and schema initialization (paper-only).

The paper engine can use PostgreSQL when DATABASE_URL is configured.
Never log DATABASE_URL; it contains a password.
"""
import os

SCHEMA = """
CREATE TABLE IF NOT EXISTS events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ts TEXT NOT NULL, symbol TEXT NOT NULL, kind TEXT NOT NULL,
 price DOUBLE PRECISION, qty INTEGER, pnl DOUBLE PRECISION, note TEXT
);
CREATE TABLE IF NOT EXISTS positions (
 symbol TEXT PRIMARY KEY, entry DOUBLE PRECISION NOT NULL,
 qty INTEGER NOT NULL, stop DOUBLE PRECISION NOT NULL,
 target DOUBLE PRECISION NOT NULL, entry_ts TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS processed (
 symbol TEXT PRIMARY KEY, ts TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS metadata (
 key TEXT PRIMARY KEY, value TEXT NOT NULL
);
"""


def get_connection(url=None):
    """Return a PostgreSQL connection; credentials stay in environment variables."""
    url = url or os.environ.get('DATABASE_URL')
    if not url:
        raise RuntimeError('DATABASE_URL is not set')
    if not url.startswith(('postgresql://', 'postgres://')):
        raise ValueError('DATABASE_URL must be a PostgreSQL URL')
    import psycopg
    return psycopg.connect(url, connect_timeout=10)


def initialize_schema(connection):
    """Create paper-account tables, without resetting existing account data."""
    with connection.transaction():
        for statement in SCHEMA.split(';'):
            if statement.strip():
                connection.execute(statement)
